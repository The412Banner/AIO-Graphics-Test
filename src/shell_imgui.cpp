static void create_timing_queries() {
    if (!g_dev) return;
    D3D11_QUERY_DESC qd;
    ZeroMemory(&qd, sizeof(qd));
    qd.Query = D3D11_QUERY_TIMESTAMP_DISJOINT;
    g_dev->CreateQuery(&qd, &g_q_disjoint);
    qd.Query = D3D11_QUERY_TIMESTAMP;
    g_dev->CreateQuery(&qd, &g_q_ts0);
    g_dev->CreateQuery(&qd, &g_q_ts1);
}
static void destroy_timing_queries() {
    if (g_q_ts1) { g_q_ts1->Release(); g_q_ts1 = nullptr; }
    if (g_q_ts0) { g_q_ts0->Release(); g_q_ts0 = nullptr; }
    if (g_q_disjoint) { g_q_disjoint->Release(); g_q_disjoint = nullptr; }
    g_q_issued = false;
}
// Read back last frame's timestamp pair (ready now - a Present has intervened, so
// no spin/stall). Updates g_scene_ms / g_scene_timed.
static void poll_timing_queries() {
    if (!g_q_issued || !g_q_disjoint) return;
    D3D11_QUERY_DATA_TIMESTAMP_DISJOINT dj;
    UINT64 a = 0, b = 0;
    if (g_ctx->GetData(g_q_disjoint, &dj, sizeof(dj), 0) == S_OK &&
        g_ctx->GetData(g_q_ts0, &a, sizeof(a), 0) == S_OK &&
        g_ctx->GetData(g_q_ts1, &b, sizeof(b), 0) == S_OK) {
        if (!dj.Disjoint && dj.Frequency > 0 && b > a) {
            g_scene_ms = (double)(b - a) * 1000.0 / (double)dj.Frequency;
            g_scene_timed = true;
        }
        g_q_issued = false;
    }
}

