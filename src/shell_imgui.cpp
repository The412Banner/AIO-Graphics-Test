// Sparkline (draw-list, area-fill gradient + endpoint dot) using real frametimes.
static void draw_sparkline(ImDrawList *dl, ImVec2 p, ImVec2 size, const float *ring, int cap,
                           int offset) {
    const int N = 60;
    float vals[N];
    float mx = 2.0f;
    for (int i = 0; i < N; ++i) {
        int idx = (offset - N + i + cap * 4) % cap;
        vals[i] = ring[idx];
        if (vals[i] > mx) mx = vals[i];
    }
    mx *= 1.15f;
    dl->AddRectFilled(p, ImVec2(p.x + size.x, p.y + size.y), IM_COL32(6, 10, 14, 128), 6.0f);
    dl->AddRect(p, ImVec2(p.x + size.x, p.y + size.y), IM_COL32(255, 255, 255, 18), 6.0f, 0, 1.0f);
    // mid grid line
    dl->AddLine(ImVec2(p.x, p.y + size.y * 0.5f), ImVec2(p.x + size.x, p.y + size.y * 0.5f),
                IM_COL32(127, 240, 228, 30), 1.0f);
    float base = p.y + size.y;
    ImU32 top = IM_COL32(47, 214, 195, 102), bot = IM_COL32(47, 214, 195, 5);
    ImVec2 pts[N];
    for (int i = 0; i < N; ++i) {
        float x = p.x + (float)i / (N - 1) * size.x;
        float y = base - (vals[i] / mx) * size.y;
        pts[i] = ImVec2(x, y);
        if (i > 0)  // vertical gradient column under the curve
            dl->AddRectFilledMultiColor(ImVec2(pts[i - 1].x, pts[i - 1].y),
                                        ImVec2(x, base), top, top, bot, bot);
    }
    dl->AddPolyline(pts, N, IM_COL32(47, 214, 195, 255), 0, 1.6f);
    dl->AddCircleFilled(pts[N - 1], 2.4f, PAL.accentInk, 12);
}

