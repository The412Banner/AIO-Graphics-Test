// Ensure the offscreen color+depth target matches (w,h) in PIXELS. Recreates only
// when the size actually changes (so a click-drag doesn't churn every frame). Also
// pushes the size into the scene layer (scaling-test scenes bake it into a CB).
static bool ensure_offscreen(int w, int h) {
    if (w < 8) w = 8;
    if (h < 8) h = 8;
    if (w == g_off_w && h == g_off_h && g_off_srv) return true;
    destroy_offscreen();

    D3D11_TEXTURE2D_DESC td;
    ZeroMemory(&td, sizeof(td));
    td.Width = (UINT)w;
    td.Height = (UINT)h;
    td.MipLevels = 1;
    td.ArraySize = 1;
    td.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
    td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_DEFAULT;
    td.BindFlags = D3D11_BIND_RENDER_TARGET | D3D11_BIND_SHADER_RESOURCE;
    if (FAILED(g_dev->CreateTexture2D(&td, nullptr, &g_off_tex))) return false;
    g_dev->CreateRenderTargetView(g_off_tex, nullptr, &g_off_rtv);
    g_dev->CreateShaderResourceView(g_off_tex, nullptr, &g_off_srv);

    D3D11_TEXTURE2D_DESC dd;
    ZeroMemory(&dd, sizeof(dd));
    dd.Width = (UINT)w;
    dd.Height = (UINT)h;
    dd.MipLevels = 1;
    dd.ArraySize = 1;
    dd.Format = DXGI_FORMAT_D24_UNORM_S8_UINT;
    dd.SampleDesc.Count = 1;
    dd.Usage = D3D11_USAGE_DEFAULT;
    dd.BindFlags = D3D11_BIND_DEPTH_STENCIL;
    g_dev->CreateTexture2D(&dd, nullptr, &g_off_depth);
    g_dev->CreateDepthStencilView(g_off_depth, nullptr, &g_off_dsv);

    // Baseline states (created once) - mirror the standalone runner: LESS depth +
    // CULL_NONE. Scenes that need other state set it themselves each frame().
    if (!g_off_dss) {
        D3D11_DEPTH_STENCIL_DESC ds;
        ZeroMemory(&ds, sizeof(ds));
        ds.DepthEnable = TRUE;
        ds.DepthWriteMask = D3D11_DEPTH_WRITE_MASK_ALL;
        ds.DepthFunc = D3D11_COMPARISON_LESS;
        g_dev->CreateDepthStencilState(&ds, &g_off_dss);
    }
    if (!g_off_rs) {
        D3D11_RASTERIZER_DESC rs;
        ZeroMemory(&rs, sizeof(rs));
        rs.FillMode = D3D11_FILL_SOLID;
        rs.CullMode = D3D11_CULL_NONE;
        rs.DepthClipEnable = TRUE;
        g_dev->CreateRasterizerState(&rs, &g_off_rs);
    }

    g_off_w = w;
    g_off_h = h;
    aio_d3d11_scene_set_size(w, h);  // keep scaling-test resolution consts correct
    return g_off_srv != nullptr;
}

