    float pillW = 12.0f + 14.0f + apiW + 12.0f + fpsW + 6.0f + text_w(g_mono_sm, 10.0f, "FPS") + 12.0f;
    float pillH = 34.0f;
    dl->AddRectFilled(hp, ImVec2(hp.x + pillW, hp.y + pillH), IM_COL32(6, 10, 14, 140), 9.0f);
    dl->AddRect(hp, ImVec2(hp.x + pillW, hp.y + pillH), IM_COL32(255, 255, 255, 20), 9.0f, 0, 1.0f);
    float hcy = hp.y + pillH * 0.5f;
    chip(dl, ImVec2(hp.x + 14.0f, hcy), 4.0f, hue_col(g_sel->hue), 3.0f);
    bold_at(dl, g_mono, 12.0f, ImVec2(hp.x + 24.0f, hcy - 6.0f), IM_COL32(255, 255, 255, 255),
            g_sel->api);
    float fx = hp.x + 24.0f + apiW + 12.0f;
    bold_at(dl, g_mono_bg, 20.0f, ImVec2(fx, hcy - 11.0f), PAL.accentInk, fpsbuf);
    text_at(dl, g_mono_sm, 10.0f, ImVec2(fx + fpsW + 4.0f, hcy - 1.0f), PAL.scrMuted, "FPS");

