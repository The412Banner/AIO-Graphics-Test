static void apply_theme(bool dark) {
    g_dark = dark;
    // Screen region colors are the same dark instrument surface in BOTH themes.
    PAL.scr = H(0x080c11); PAL.scr2 = H(0x0c1219); PAL.scrLine = H(0x1b2530);
    PAL.scrText = H(0xdce6ef); PAL.scrMuted = H(0x7d8b9b);
    PAL.good = H(0x2fae5f); PAL.warn = H(0xd99626); PAL.bad = H(0xe5484d);
    if (dark) {
        PAL.bg = H(0x070a0e); PAL.bg2 = H(0x0a0e13); PAL.panel = H(0x0f151c);
        PAL.panel2 = H(0x131b24); PAL.panelhi = H(0x18222d); PAL.line = H(0x212c38);
        PAL.line2 = H(0x2c3b4b); PAL.text = H(0xe3ebf3); PAL.muted = H(0x8a97a6);
        PAL.faint = H(0x5f6c7c); PAL.accent = H(0x2fd6c3); PAL.accentInk = H(0x7ff0e4);
    } else {
        PAL.bg = H(0xe9edf1); PAL.bg2 = H(0xdfe4ea); PAL.panel = H(0xffffff);
        PAL.panel2 = H(0xf2f5f8); PAL.panelhi = H(0xe8edf2); PAL.line = H(0xd6dce3);
        PAL.line2 = H(0xc3ccd6); PAL.text = H(0x141b23); PAL.muted = H(0x5b6775);
        PAL.faint = H(0x8592a0); PAL.accent = H(0x0f9e8f); PAL.accentInk = H(0x0b7a6e);
    }

    // The render viewport now follows the theme (fix 6): light backdrop + light
    // cube clear in light mode, the dark instrument surface in dark mode. The clear
    // is mirrored to the cross-API embedded backends via aio_embed_clear_rgb.
    if (dark) {
        g_view_bg = PAL.scr; g_view_bg2 = PAL.scr2;
        g_scene_clear[0] = 8.0f / 255.0f; g_scene_clear[1] = 12.0f / 255.0f; g_scene_clear[2] = 17.0f / 255.0f;
    } else {
        g_view_bg = H(0xdfe4ea); g_view_bg2 = H(0xeef2f6);
        g_scene_clear[0] = 0xe6 / 255.0f; g_scene_clear[1] = 0xea / 255.0f; g_scene_clear[2] = 0xef / 255.0f;
    }
    aio_embed_clear_rgb[0] = g_scene_clear[0];
    aio_embed_clear_rgb[1] = g_scene_clear[1];
    aio_embed_clear_rgb[2] = g_scene_clear[2];

    ImGuiStyle &s = ImGui::GetStyle();
    if (dark) ImGui::StyleColorsDark(); else ImGui::StyleColorsLight();
    s.WindowRounding = 0.0f; s.ChildRounding = 10.0f; s.FrameRounding = 7.0f;
    s.GrabRounding = 6.0f; s.ScrollbarRounding = 6.0f; s.PopupRounding = 8.0f;
    s.WindowBorderSize = 0.0f; s.ChildBorderSize = 0.0f; s.FrameBorderSize = 0.0f;
    s.ScrollbarSize = 10.0f;
    s.Colors[ImGuiCol_WindowBg] = V(dark ? 0x0f151c : 0xffffff);
    s.Colors[ImGuiCol_ChildBg] = ImVec4(0, 0, 0, 0);
    s.Colors[ImGuiCol_Text] = V(dark ? 0xe3ebf3 : 0x141b23);
    s.Colors[ImGuiCol_TextDisabled] = V(dark ? 0x5f6c7c : 0x8592a0);
    s.Colors[ImGuiCol_Border] = V(dark ? 0x212c38 : 0xd6dce3);
    s.Colors[ImGuiCol_ScrollbarBg] = ImVec4(0, 0, 0, 0);
    s.Colors[ImGuiCol_ScrollbarGrab] = V(dark ? 0x2c3b4b : 0xc3ccd6);
    s.Colors[ImGuiCol_ScrollbarGrabHovered] = V(dark ? 0x5f6c7c : 0x8592a0);
    s.Colors[ImGuiCol_ScrollbarGrabActive] = V(dark ? 0x2fd6c3 : 0x0f9e8f);
    s.Colors[ImGuiCol_FrameBg] = ImVec4(0, 0, 0, 0);
}

