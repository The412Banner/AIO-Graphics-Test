        float chipY = ry + ROWH * 0.5f;
        chip(dl, ImVec2(x0 + 5.0f, chipY), 4.0f, hue_col(r.hue));
        text_at(dl, g_mono, 11.5f, ImVec2(x0 + 14.0f, ry + 8.0f), PAL.scrText, r.label);
