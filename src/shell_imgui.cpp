// Expand (windowed) / collapse (fullscreen) corner glyph: opposite-corner brackets.
static void draw_fs_icon(ImDrawList *dl, ImVec2 c, float r, bool collapse, ImU32 col) {
    const float t = 1.7f;
    if (!collapse) {
        // expand: arrowheads pushed OUT to the top-left / bottom-right corners
        ImVec2 tl(c.x - r, c.y - r), br(c.x + r, c.y + r);
        dl->AddLine(tl, br, col, t);
        dl->AddLine(tl, ImVec2(tl.x + r * 0.9f, tl.y), col, t);
        dl->AddLine(tl, ImVec2(tl.x, tl.y + r * 0.9f), col, t);
        dl->AddLine(br, ImVec2(br.x - r * 0.9f, br.y), col, t);
        dl->AddLine(br, ImVec2(br.x, br.y - r * 0.9f), col, t);
    } else {
        // collapse: arrowheads pulled IN toward the center
        ImVec2 tl(c.x - r, c.y - r), br(c.x + r, c.y + r);
        ImVec2 itl(c.x - r * 0.15f, c.y - r * 0.15f), ibr(c.x + r * 0.15f, c.y + r * 0.15f);
        dl->AddLine(tl, itl, col, t);
        dl->AddLine(itl, ImVec2(itl.x - r * 0.9f, itl.y), col, t);
        dl->AddLine(itl, ImVec2(itl.x, itl.y - r * 0.9f), col, t);
        dl->AddLine(br, ibr, col, t);
        dl->AddLine(ibr, ImVec2(ibr.x + r * 0.9f, ibr.y), col, t);
        dl->AddLine(ibr, ImVec2(ibr.x, ibr.y + r * 0.9f), col, t);
    }
}

