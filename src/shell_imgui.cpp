static inline ImU32 H(unsigned rgb, int a = 255) {
    return IM_COL32((rgb >> 16) & 0xff, (rgb >> 8) & 0xff, rgb & 0xff, a);
}
static inline ImVec4 V(unsigned rgb, float a = 1.0f) {
    return ImVec4(((rgb >> 16) & 0xff) / 255.0f, ((rgb >> 8) & 0xff) / 255.0f,
                  (rgb & 0xff) / 255.0f, a);
}

