// Expand (windowed) / collapse (fullscreen) corner glyph: opposite-corner brackets.
static void draw_fs_icon(ImDrawList *dl, ImVec2 c, float r, bool collapse, ImU32 col) {
    const float t = 1.7f;
    if (!collapse) {
        // expand: arrowheads pushed OUT to the top-left / bottom-right corners
        ImVec2 tl(c.x - r, c.y - r), br(c.x + r, c.y + r);
        dl->AddLine(tl, br, col, t);
        dl->AddLine(tl, ImVec2(tl.x + r * 0.9f, tl.y), col, t);
        dl->AddLine(tl, ImVec2(tl.x, tl.y + r * 0.9f), col, t);
        dl->AddLine(br, ImVec2(br.x - r * 0.9f, br.y), col, t);
        dl->AddLine(br, ImVec2(br.x, br.y - r * 0.9f), col, t);
    } else {
        // collapse: arrowheads pulled IN toward the center
        ImVec2 tl(c.x - r, c.y - r), br(c.x + r, c.y + r);
        ImVec2 itl(c.x - r * 0.15f, c.y - r * 0.15f), ibr(c.x + r * 0.15f, c.y + r * 0.15f);
        dl->AddLine(tl, itl, col, t);
        dl->AddLine(itl, ImVec2(itl.x - r * 0.9f, itl.y), col, t);
        dl->AddLine(itl, ImVec2(itl.x, itl.y - r * 0.9f), col, t);
        dl->AddLine(br, ibr, col, t);
        dl->AddLine(ibr, ImVec2(ibr.x + r * 0.9f, ibr.y), col, t);
        dl->AddLine(ibr, ImVec2(ibr.x, ibr.y + r * 0.9f), col, t);
    }
}

// Touch-sized fullscreen toggle pinned to the viewport's top-right. In fullscreen
// it widens into an always-visible "Exit Fullscreen" pill so the way back is
// obvious on a touchscreen. Returns true when tapped/clicked.
static bool fs_toggle_control(float right_x, float top_y, bool fs) {
    ImDrawList *dl = ImGui::GetWindowDrawList();
    const float H = 34.0f, PAD = 12.0f, ICON = 18.0f;
    const char *label = fs ? "Exit Fullscreen" : nullptr;
    float labW = label ? text_w(g_ui, 13.0f, label) : 0.0f;
    float w = label ? (14.0f + ICON + 8.0f + labW + 14.0f) : H;  // icon-only square when windowed
    ImVec2 p(right_x - PAD - w, top_y + PAD), mx(p.x + w, p.y + H);
    ImGui::SetCursorScreenPos(p);
    ImGui::PushID("##fsctl");
    bool clk = ImGui::InvisibleButton("c", ImVec2(w, H));
    bool hov = ImGui::IsItemHovered();
    ImGui::PopID();
    dl->AddRectFilled(p, mx, IM_COL32(6, 10, 14, hov ? 225 : 150), 9.0f);
    dl->AddRect(p, mx, hov ? PAL.accent : IM_COL32(255, 255, 255, 30), 9.0f, 0, 1.2f);
    ImU32 ic = hov ? PAL.accentInk : PAL.scrText;
    float cy = (p.y + mx.y) * 0.5f;
    float ix = label ? (p.x + 14.0f + ICON * 0.5f) : (p.x + w * 0.5f);
    draw_fs_icon(dl, ImVec2(ix, cy), 6.0f, fs, ic);
    if (label) text_at(dl, g_ui, 13.0f, ImVec2(p.x + 14.0f + ICON + 8.0f, cy - 7.0f), ic, label);
    return clk;
}

// ===========================================================================
// Entry point.
// ===========================================================================
extern "C" int aio_run_imgui_shell(HINSTANCE hInstance) {
    WNDCLASSEXA wc;
    ZeroMemory(&wc, sizeof(wc));
    wc.cbSize = sizeof(wc);
    wc.style = CS_HREDRAW | CS_VREDRAW;
    wc.lpfnWndProc = wnd_proc;
    wc.hInstance = hInstance;
    wc.hCursor = LoadCursor(nullptr, IDC_ARROW);
    wc.lpszClassName = "AIOImGuiShell";
    RegisterClassExA(&wc);

    HWND hwnd = CreateWindowA(wc.lpszClassName, "AIO Graphics Test", WS_OVERLAPPEDWINDOW, 100, 100,
                              1180, 720, nullptr, nullptr, hInstance, nullptr);
    if (!hwnd) {
        UnregisterClassA(wc.lpszClassName, hInstance);
        return 1;
    }

    if (!create_device(hwnd)) {
        destroy_device();
        DestroyWindow(hwnd);
        UnregisterClassA(wc.lpszClassName, hInstance);
        MessageBoxA(nullptr,
                    "Direct3D 11 is not available in this container.\n\n"
                    "Could not create a D3D11 device + swapchain (no d3d11.dll / DXVK?).\n"
                    "The ImGui shell requires the container's DXVK DLL set.",
                    "AIO Graphics Test", MB_OK | MB_ICONERROR);
        return 1;
    }

    ShowWindow(hwnd, SW_SHOWDEFAULT);
    UpdateWindow(hwnd);

    IMGUI_CHECKVERSION();
    ImGui::CreateContext();
    ImGuiIO &io = ImGui::GetIO();
    io.IniFilename = nullptr;  // do not persist layout

    // Embedded fonts.
    ImFontConfig cfg;
    cfg.OversampleH = 3; cfg.OversampleV = 2; cfg.PixelSnapH = false;
    g_ui = io.Fonts->AddFontFromMemoryCompressedBase85TTF(InterUI_compressed_data_base85, 14.0f, &cfg);
    g_ui_big = io.Fonts->AddFontFromMemoryCompressedBase85TTF(InterUI_compressed_data_base85, 19.0f, &cfg);
    g_mono = io.Fonts->AddFontFromMemoryCompressedBase85TTF(CascadiaMono_compressed_data_base85, 12.0f, &cfg);
    g_mono_sm = io.Fonts->AddFontFromMemoryCompressedBase85TTF(CascadiaMono_compressed_data_base85, 10.0f, &cfg);
    g_mono_bg = io.Fonts->AddFontFromMemoryCompressedBase85TTF(CascadiaMono_compressed_data_base85, 20.0f, &cfg);
    io.FontDefault = g_ui;

    init_hues();
    apply_theme(true);  // dark default
    ImGui_ImplWin32_Init(hwnd);
    ImGui_ImplDX11_Init(g_dev, g_ctx);

    // Real frametime ring buffer + absolute clock (scene animation time).
    static float frametimes[120];
    for (int i = 0; i < 120; ++i) frametimes[i] = 16.6f;
    int ft_offset = 0;
    LARGE_INTEGER freq, prev, start;
    QueryPerformanceFrequency(&freq);
    QueryPerformanceCounter(&prev);
    start = prev;
    float fps_smooth = 0.0f;
    const Test *last_launched = nullptr;  // dedupe standalone-backend launches

    bool done = false;
    while (!done) {
        MSG msg;
        while (PeekMessage(&msg, nullptr, 0, 0, PM_REMOVE)) {
            TranslateMessage(&msg);
            DispatchMessage(&msg);
            if (msg.message == WM_QUIT) done = true;
        }
        if (done) break;

        // Apply one coalesced swapchain resize per frame (click-drag safe).
        if (g_resize_w != 0 && g_dev) {
            UINT nw = g_resize_w, nh = g_resize_h;
            g_resize_w = g_resize_h = 0;
            if (nw > 0 && nh > 0) {
                release_rtv();
                g_swap->ResizeBuffers(0, nw, nh, DXGI_FORMAT_UNKNOWN, 0);
                create_rtv();
            }
        }

        LARGE_INTEGER now;
        QueryPerformanceCounter(&now);
        double dt_ms = (double)(now.QuadPart - prev.QuadPart) * 1000.0 / (double)freq.QuadPart;
        prev = now;
        if (dt_ms < 0.0) dt_ms = 0.0;
        double t_sec = (double)(now.QuadPart - start.QuadPart) / (double)freq.QuadPart;
        frametimes[ft_offset] = (float)dt_ms;
        ft_offset = (ft_offset + 1) % 120;
        float inst_fps = dt_ms > 0.0 ? (float)(1000.0 / dt_ms) : 0.0f;
        fps_smooth = fps_smooth <= 0.0f ? inst_fps : fps_smooth * 0.9f + inst_fps * 0.1f;

        ImGui_ImplDX11_NewFrame();
        ImGui_ImplWin32_NewFrame();
        ImGui::NewFrame();

        ImGuiViewport *vp = ImGui::GetMainViewport();
        ImVec2 o = vp->WorkPos;
        float W = vp->WorkSize.x, Hh = vp->WorkSize.y;
        if (W < 1.0f) W = 1.0f;
        if (Hh < 1.0f) Hh = 1.0f;
        ImGui::SetNextWindowPos(o);
        ImGui::SetNextWindowSize(ImVec2(W, Hh));
        ImGui::PushStyleVar(ImGuiStyleVar_WindowPadding, ImVec2(0, 0));
        ImGuiWindowFlags rflags = ImGuiWindowFlags_NoTitleBar | ImGuiWindowFlags_NoResize |
                                  ImGuiWindowFlags_NoMove | ImGuiWindowFlags_NoScrollbar |
                                  ImGuiWindowFlags_NoScrollWithMouse | ImGuiWindowFlags_NoCollapse |
                                  ImGuiWindowFlags_NoSavedSettings | ImGuiWindowFlags_NoBringToFrontOnFocus |
                                  ImGuiWindowFlags_NoNavFocus;
        ImGui::Begin("##root", nullptr, rflags);
        ImDrawList *dl = ImGui::GetWindowDrawList();

        const float TITLE_H = 34.0f, TOOL_H = 40.0f, FOOT_H = 34.0f, PANEL_W = 320.0f;
        float bodyTop = o.y + TITLE_H + TOOL_H;
        float bodyH = Hh - TITLE_H - TOOL_H - FOOT_H;
        float vpW = W - PANEL_W;
        if (vpW < 8.0f) vpW = 8.0f;
        if (bodyH < 8.0f) bodyH = 8.0f;

        // Active viewport rect (fullscreen = whole window). The offscreen target is
        // recreated to THIS pixel size, so aspect stays correct with no stretching.
        float rvW = g_fullscreen ? W : vpW;
        float rvH = g_fullscreen ? Hh : bodyH;
        render_scene_to_offscreen((int)rvW, (int)rvH, t_sec);

        if (g_fullscreen) {
            draw_viewport(dl, o, W, Hh, fps_smooth, frametimes, 120, ft_offset, true);
        } else {
            dl->AddRectFilled(o, ImVec2(o.x + W, o.y + Hh), PAL.bg, 0);
            draw_titlebar(dl, o, W, TITLE_H);
            draw_toolbar(dl, ImVec2(o.x, o.y + TITLE_H), W, TOOL_H);
            draw_viewport(dl, ImVec2(o.x, bodyTop), vpW, bodyH, fps_smooth, frametimes, 120,
                          ft_offset, false);
            draw_menu(dl, ImVec2(o.x + vpW, bodyTop), PANEL_W, bodyH);
            draw_footer(dl, ImVec2(o.x, o.y + Hh - FOOT_H), W, FOOT_H);
        }

        // Fullscreen toggle control, pinned to the active viewport's top-right. Only
        // shown for the embeddable in-viewport render (not tools / launched backends).
        bool can_fs = !g_sel->tool && !launch_arg_for(g_sel, g_sel_group);
        if (can_fs || g_fullscreen) {
            float fsRight = g_fullscreen ? (o.x + W) : (o.x + vpW);
            float fsTop = g_fullscreen ? o.y : bodyTop;
            if (fs_toggle_control(fsRight, fsTop, g_fullscreen)) g_fullscreen = !g_fullscreen;
        }

        ImGui::End();
        ImGui::PopStyleVar();

        // Launch a standalone window for a non-embeddable backend on selection change
        // (deduped so it doesn't relaunch every frame; reselecting relaunches).
        const char *larg = launch_arg_for(g_sel, g_sel_group);
        if (larg) {
            if (g_sel != last_launched) { launch_backend(larg); last_launched = g_sel; }
        } else {
            last_launched = nullptr;
        }

        ImGui::Render();
        const float clear[4] = {0.027f, 0.039f, 0.055f, 1.0f};
        g_ctx->OMSetRenderTargets(1, &g_rtv, nullptr);
        g_ctx->ClearRenderTargetView(g_rtv, clear);
        ImGui_ImplDX11_RenderDrawData(ImGui::GetDrawData());
        g_swap->Present(1, 0);
    }

    if (g_cur_scene >= 0) aio_d3d11_scene_cleanup(g_cur_scene);
    destroy_offscreen();
    if (g_off_dss) { g_off_dss->Release(); g_off_dss = nullptr; }
    if (g_off_rs) { g_off_rs->Release(); g_off_rs = nullptr; }
    ImGui_ImplDX11_Shutdown();
    ImGui_ImplWin32_Shutdown();
    ImGui::DestroyContext();
    destroy_device();
    DestroyWindow(hwnd);
    UnregisterClassA(wc.lpszClassName, hInstance);
    return 0;
}
